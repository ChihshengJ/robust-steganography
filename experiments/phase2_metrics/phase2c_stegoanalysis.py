def _stat(values: list[float]) -> dict:
    if not values:
        return {"n": 0}
    return {
        "n": len(values),
        "mean": float(np.mean(values)),
        "std": float(np.std(values, ddof=0)),
    }


def _agg_folds(folds: list[dict]) -> dict:
    keys = ["accuracy", "f1", "auc"]
    mean = {
        k: _stat([f[k] for f in folds if f.get(k) is not None])["mean"] for k in keys
    }
    std = {k: _stat([f[k] for f in folds if f.get(k) is not None])["std"] for k in keys}
    return {"folds": folds, "mean": mean, "std": std}


def _cv_logreg(X: np.ndarray, y: np.ndarray) -> dict:
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_SEED)
    folds = []
    for fold_idx, (train_idx, test_idx) in enumerate(skf.split(X, y)):
        scaler = StandardScaler()
        X_train = scaler.fit_transform(X[train_idx])
        X_test = scaler.transform(X[test_idx])
        clf = LogisticRegression(max_iter=1000, solver="lbfgs")
        clf.fit(X_train, y[train_idx])
        proba = clf.predict_proba(X_test)[:, 1]
        pred = (proba >= 0.5).astype(int)
        folds.append(
            {
                "fold": fold_idx,
                "n_train": len(train_idx),
                "n_test": len(test_idx),
                "accuracy": float(accuracy_score(y[test_idx], pred)),
                "f1": float(f1_score(y[test_idx], pred, average="macro")),
                "auc": (
                    float(roc_auc_score(y[test_idx], proba))
                    if len(np.unique(y[test_idx])) > 1
                    else None
                ),
            }
        )
    return _agg_folds(folds)


