def _embed_with_transformers(texts: list[str], model_name: str) -> np.ndarray:
    """Mean-pooled last-hidden-state embeddings via raw HF transformers."""
    import torch
    from transformers import AutoModel, AutoTokenizer

    if torch.cuda.is_available():
        device = "cuda"
    elif torch.backends.mps.is_available():
        device = "mps"
    else:
        device = "cpu"

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModel.from_pretrained(model_name).to(device)
    model.eval()

    embeddings = []
    batch_size = 4
    with torch.no_grad():
        for i in range(0, len(texts), batch_size):
            batch = texts[i : i + batch_size]
            enc = tokenizer(
                batch,
                truncation=True,
                padding=True,
                max_length=512,
                return_tensors="pt",
            ).to(device)
            out = model(**enc)
            hidden = out.last_hidden_state
            mask = enc["attention_mask"].unsqueeze(-1).float()
            summed = (hidden * mask).sum(dim=1)
            counts = mask.sum(dim=1).clamp(min=1e-9)
            mean_pooled = summed / counts
            embeddings.append(mean_pooled.cpu().float().numpy())
    return np.vstack(embeddings)


def _embed_with_sentence_transformers(texts: list[str], model_name: str) -> np.ndarray:
    from sentence_transformers import SentenceTransformer

    model = SentenceTransformer(model_name)
    return np.asarray(model.encode(texts, show_progress_bar=False))


def _embed_with_llamacpp(
    texts: list[str],
    model_name: str,
    base_url: str,
    instruction: str,
    batch_size: int = 16,
) -> np.ndarray:
    """Embeddings via llama.cpp's OpenAI-compatible /v1/embeddings endpoint.

    Launch the server with ``--embeddings`` and a Qwen3-Embedding GGUF, e.g.::

        llama-server -m /path/to/Qwen3-Embedding-8B-Q8_0.gguf \\
            --embeddings --port 11435 --ctx-size 8192

    ``model_name`` is the label sent in the request body; llama.cpp serves
    whichever model was loaded at startup, so the value is mostly cosmetic.
    """
    import openai

    client = openai.OpenAI(base_url=base_url, api_key="unused")
    formatted = [f"Instruct: {instruction}\nQuery: {t}" for t in texts]

    embeddings: list[list[float]] = []
    for i in range(0, len(formatted), batch_size):
        chunk = formatted[i : i + batch_size]
        for attempt in range(3):
            try:
                resp = client.embeddings.create(model=model_name, input=chunk)
                break
            except Exception as e:
                if attempt == 2:
                    raise
                log.warning("  embeddings retry %d (chunk %d): %s", attempt + 1, i, e)
                time.sleep(2**attempt)
        embeddings.extend(item.embedding for item in resp.data)

    return np.asarray(embeddings, dtype=np.float32)


def run_embedding_baseline(
    texts: list[str],
    y: np.ndarray,
    embedder: str,
    backend: str,
    base_url: str,
    instruction: str,
) -> dict:
    log.info(
        "  embedding via backend=%s model=%s (n=%d)", backend, embedder, len(texts)
    )
    if backend == "llamacpp":
        X = _embed_with_llamacpp(texts, embedder, base_url, instruction)
    elif backend == "sbert":
        X = _embed_with_sentence_transformers(texts, embedder)
    elif backend == "hf":
        X = _embed_with_transformers(texts, embedder)
    else:
        raise ValueError(f"Unknown embedder backend: {backend}")
    log.info("  embeddings shape=%s", X.shape)
    result = _cv_logreg(X, y)
    result["embedder"] = embedder
    result["embedder_backend"] = backend
    result["embedding_dim"] = int(X.shape[1])
    if backend == "llamacpp":
        result["embedder_base_url"] = base_url
        result["embedder_instruction"] = instruction
    return result


