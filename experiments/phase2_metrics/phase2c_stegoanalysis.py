def _load_perplexity_map(data_dir: Path) -> dict[str, float]:
    path = data_dir / "phase2_metrics" / "perplexity_all.jsonl"
    records = read_jsonl(path)
    if not records:
        raise FileNotFoundError(
            f"No perplexity records at {path}. Run phase2b_perplexity first."
        )
    return {r["id"]: r["perplexity"] for r in records if "perplexity" in r}


def run_perplexity_only(
    stego_recs: list[dict],
    cover_recs: list[dict],
    ppl_map: dict[str, float],
) -> dict:
    pairs = []
    missing = 0
    for label, recs in [(1, stego_recs), (0, cover_recs)]:
        for r in recs:
            ppl = ppl_map.get(r["id"])
            if ppl is None or ppl == float("inf"):
                missing += 1
                continue
            pairs.append((ppl, label))
    if missing:
        log.warning("  perplexity-only: %d records missing perplexity values", missing)

    if not pairs:
        return {"error": "no perplexity values available"}

    X = np.array([[p[0]] for p in pairs])
    y = np.array([p[1] for p in pairs])
    return _cv_logreg(X, y)


def run_perplexity_test(
    stego_recs: list[dict],
    cover_recs: list[dict],
    ppl_map: dict[str, float],
) -> dict:
    s_vals = [ppl_map[r["id"]] for r in stego_recs if r["id"] in ppl_map]
    c_vals = [ppl_map[r["id"]] for r in cover_recs if r["id"] in ppl_map]
    s_vals = [v for v in s_vals if v != float("inf")]
    c_vals = [v for v in c_vals if v != float("inf")]
    if not s_vals or not c_vals:
        return {"error": "missing perplexity values for one side"}

    u, p = mannwhitneyu(s_vals, c_vals, alternative="two-sided")
    n1, n2 = len(s_vals), len(c_vals)
    rank_biserial = 1.0 - (2.0 * u) / (n1 * n2)
    return {
        "u_stat": float(u),
        "p_value": float(p),
        "n_stego": n1,
        "n_cover": n2,
        "median_stego": float(np.median(s_vals)),
        "median_cover": float(np.median(c_vals)),
        "rank_biserial": float(rank_biserial),
    }


